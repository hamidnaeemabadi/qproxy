# shellcheck shell=bash
# Shell completion candidates shared by the Bash and Zsh generators.
qproxy_completion_words() {
    case "$1:$2:$3" in
        1:*) echo 'install uninstall config enable disable test completion help --help -h' ;;
        2:install:*) echo 'status --no-deps --completions --proxychains-conf --force-proxychains-conf --prefix --help -h' ;;
        *:install:status) ;;
        *:install:*) echo '--no-deps --completions --proxychains-conf --force-proxychains-conf --prefix --help -h' ;;
        2:config:*) echo show ;;
        2:enable:*|2:disable:*) echo 'os-env apt pkgmgr docker docker-cli containerd proxychains' ;;
        2:test:*) echo 'health apt pkgmgr docker docker-cli containerd proxychains' ;;
        2:completion:*) echo 'bash zsh install --help -h' ;;
        3:enable:os-env|3:enable:apt|3:test:health) echo 'http socks5' ;;
        3:enable:docker|3:enable:docker-cli|3:enable:containerd) echo 'http socks5h socks5' ;;
        3:enable:proxychains) echo 'http socks5 dual' ;;
        3:enable:pkgmgr) echo http ;;
    esac
}

qproxy_completion_generate() {
    case "${1:-}" in
        bash|zsh) ;;
        *) echo 'Usage: qproxy completion bash|zsh|install' >&2; return 1 ;;
    esac
    if [ "$1" = zsh ]; then
        echo '#compdef qproxy qproxy.sh'
    else
        echo '# shellcheck shell=bash'
    fi
    declare -f qproxy_completion_words
    if [ "$1" = bash ]; then
        cat <<'EOF'
_qproxy() {
    local cur="${COMP_WORDS[COMP_CWORD]}" candidate
    COMPREPLY=()
    if [ "${COMP_WORDS[1]}" = install ] && [ "${COMP_WORDS[COMP_CWORD-1]}" = --prefix ]; then
        while IFS= read -r candidate; do
            COMPREPLY+=("$candidate")
        done < <(compgen -d -- "$cur")
        compopt -o filenames 2>/dev/null || true
    else
        while IFS= read -r candidate; do
            COMPREPLY+=("$candidate")
        done < <(compgen -W "$(qproxy_completion_words "$COMP_CWORD" "${COMP_WORDS[1]}" "${COMP_WORDS[2]}")" -- "$cur")
    fi
}
complete -F _qproxy qproxy qproxy.sh ./qproxy.sh
EOF
    else
        cat <<'EOF'
_qproxy() {
    local candidates
    if [[ ${words[2]} == install && ${words[CURRENT-1]} == --prefix ]]; then
        _directories
    else
        candidates=$(qproxy_completion_words "$((CURRENT-1))" "${words[2]}" "${words[3]}")
        [[ -z $candidates ]] || compadd -- ${=candidates}
    fi
}
if [[ ${funcstack[1]} == _qproxy ]]; then
    _qproxy "$@"
else
    compdef _qproxy qproxy qproxy.sh ./qproxy.sh
fi
EOF
    fi
}

qproxy_completion_path() {
    local prefix="$QPROXY_INSTALL_PREFIX"
    if [ "$(detect_os)" = darwin ]; then
        prefix=$(qproxy_brew_prefix 2>/dev/null) || prefix="$QPROXY_INSTALL_PREFIX"
        if [ "$1" = bash ]; then
            echo "$prefix/etc/bash_completion.d/qproxy"
            return
        fi
    fi
    case "$1" in
        bash) echo "$prefix/share/bash-completion/completions/qproxy" ;;
        zsh) echo "$prefix/share/zsh/site-functions/_qproxy" ;;
    esac
}

qproxy_completion_install() {
    local shell dest tmp
    for shell in bash zsh; do
        dest=$(qproxy_completion_path "$shell") || return 1
        tmp=$(mktemp) || return 1
        if ! qproxy_completion_generate "$shell" > "$tmp" ||
            ! install -d "$(dirname "$dest")" || ! install -m 0644 "$tmp" "$dest"; then
            rm -f "$tmp"
            return 1
        fi
        rm -f "$tmp"
        echo "Installed $shell completion: $dest"
    done
    echo 'Restart your shell. Bash needs bash-completion loaded; Zsh needs compinit enabled.'
}

qproxy_completion_uninstall() {
    local shell dest
    for shell in bash zsh; do
        dest=$(qproxy_completion_path "$shell") || return 1
        # Only remove completion scripts generated by QProxy.
        if [ -f "$dest" ] && grep -q 'qproxy_completion_words' "$dest"; then
            rm -f "$dest" || return 1
        fi
    done
}
